def normalized(value):
    return ' '.join(unicodedata.normalize('NFKC',value or '').casefold().split())

def overlay(payload):
    if payload.get('source_snapshot_sha')!=SOURCE_SHA:
        return payload
    rows=[]
    for p in payload['categories']:
        review=REVIEW.get(p['product_id'])
        # Refuse to reuse the mapping if a source ID/label ever diverges.
        if review and p.get('name_source')==review[0] and p.get('kind') in ('review','part'):
            p={**p,'kind':'part','name_uk':review[1],'pilot_reviewed':True,
               'candidate_aliases':list(review[2])}
        rows.append(p)
    return {**payload,'categories':rows}

def candidates(row, products):
    # Names identify suggestions for inspection, never a fitment or an OEM assignment.
    name=normalized(row.name)
    if not name:return []
    return [p['product_id'] for p in products if p.get('kind')=='part' and
            name in {normalized(n) for n in [p.get('name_uk'),*p.get('candidate_aliases',[])] if n}]


def row_identity(row):
    from app.services.catalogue_format import digest
    return digest([row.id,row.source,row.catalog_key,row.name,row.position,
                   row.category_name,row.subcategory_name])


def reference_matches(ref, row, vehicle_basis):
    return bool(ref and ref.get('vehicle_basis')==vehicle_basis and
                ref.get('row_identity')==row_identity(row))

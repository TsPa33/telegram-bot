 const headers={'X-CSRF-Token':(await auth.json()).csrf_token};
 async function post(path,data){const r=await c.request.post(origin+'/api/v1'+path,{headers,data});assert(r.ok(),await r.text());return r.json();}
 async function get(path){const r=await c.request.get(origin+'/api/v1'+path);assert(r.ok(),await r.text());return r.json();}
 const v=await post('/vehicles',{manufacturer:'Volvo',model:'XC60 mobile QA',year:2016});
 const part=await post('/parts',{name:'Генератор Mobile QA',vehicle_id:v.id,selling_price:'5900.00',currency:'UAH',oem_number:'MOBILE-QA-123'});
 await post('/parts/'+part.id+'/operations',{type:'receipt',quantity:3,reason:'Synthetic mobile QA'});
 const buyer=await post('/buyers',{name:'Покупець Mobile QA',phone:'0505558877'});
 await page.goto(origin+'/');
 const search=page.getByRole('combobox',{name:'Пошук запчастин'});
 await expect(search).toBeVisible();
 const categories=page.locator('.mobile-search-categories');
 await expect(categories).not.toHaveAttribute('open','');
 const box=await search.boundingBox();assert(box.y<280,'Search must be above the fold');
 await expect(page.getByRole('combobox',{name:'Оформлення',exact:true})).toBeVisible();
 await page.getByRole('combobox',{name:'Оформлення',exact:true}).selectOption('gold');
 await expect(page.locator('html')).toHaveAttribute('data-night-style','gold');
 await page.screenshot({path:out+'/search-first-390.png'});
 await page.getByRole('button',{name:'Фільтри',exact:true}).click();
 await expect(page.getByRole('combobox',{name:'Автомобіль пошуку'})).toBeVisible();
 await page.getByRole('button',{name:'Фільтри',exact:true}).click();
 await categories.locator('summary').click();
 await expect(categories.locator('.ui11-category-grid').first()).toBeVisible();
 await categories.locator('summary').click();
 await search.fill('MOBILE-QA-123');
 await page.getByRole('button',{name:'Знайти',exact:true}).click();
 const card=page.getByRole('article',{name:part.name,exact:true});
 await expect(card).toBeVisible();
 await expect(card).toContainText('MOBILE-QA-123');
 await expect(card).toContainText('В наявності · 3 шт.');
 await expect(page.locator('.mobile-search-result')).toHaveCount(1);
 await card.getByRole('button',{name:'Деталі запчастини',exact:true}).click();
 await expect(page.getByRole('button',{name:'Закрити швидкий перегляд'})).toBeVisible();
 await page.getByRole('button',{name:'Закрити швидкий перегляд'}).click();
 await page.screenshot({path:out+'/result-390.png'});
 await card.getByRole('button',{name:'Оформити',exact:true}).click();
 const dialog=page.getByRole('dialog',{name:'Оформити замовлення',exact:true});
 await expect(dialog).toBeVisible();
 await expect(dialog.locator('.mobile-checkout-total')).toBeVisible();
 await dialog.getByRole('button',{name:'Збільшити кількість '+part.name}).click();
 await expect(dialog.getByRole('spinbutton',{name:'Кількість '+part.name})).toHaveValue('2');
 await expect(dialog.locator('.mobile-checkout-total')).toContainText('11');
 await dialog.getByRole('button',{name:'Зменшити кількість '+part.name}).click();
 await dialog.getByRole('textbox',{name:'Телефон покупця',exact:true}).fill(buyer.phone);
 await dialog.getByRole('button',{name:/Покупець Mobile QA/}).click();
 await expect(dialog.locator('.order-buyer-selected')).toBeVisible();
 await dialog.getByRole('combobox',{name:'Доставка',exact:true}).selectOption('branch');
 await dialog.getByRole('textbox',{name:'Місто',exact:true}).fill('Київ');
 await dialog.getByRole('textbox',{name:'Відділення',exact:true}).fill('Тестове відділення');

 page.on('pageerror',e=>errors.push(e.message));
 const auth=await c.request.post(origin+'/api/v1/auth/register',{data:{name:'Mobile search QA',email:'mobile-'+crypto.randomUUID()+'@example.test',password:'isolated-mobile-test-password'}});

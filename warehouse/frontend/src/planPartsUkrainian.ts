function normalizedSource(name:string){
 return name.normalize('NFKC').trim().replace(/\s+/g,' ').replace(/\s*,\s*/g,', ').toLocaleLowerCase('en-US');
}

/** Returns verified glossary rendering, preserving source for anything unknown. */
export function ukrainianPartName(name:string):{uk:string;original:string;translated:boolean}{
 const original=String(name||'').trim();
 const key=normalizedSource(original);
 const uk=exact[key];
 return {uk:uk??original,original,translated:Boolean(uk)};
}

export function translatedCategoryCount(names:string[]):number{
 return names.filter(name=>ukrainianPartName(name).translated).length;
}
